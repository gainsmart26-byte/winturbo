create table if not exists public.chatbot_settings (
  id boolean primary key default true check (id),
  bot_name text not null default 'TurboMan',
  enabled boolean not null default true,
  access_mode text not null default 'domain' check (access_mode in ('domain','ip','both')),
  allowed_origins text[] not null default array['winturbo.com','www.winturbo.com','winturbo.vercel.app']::text[],
  allowed_ips text[] not null default '{}'::text[],
  supported_languages text[] not null default array['English','Hindi','Hinglish','Punjabi','Bengali','Marathi','Gujarati','Tamil','Telugu','Kannada','Malayalam']::text[],
  welcome_message text not null default 'TurboMan is here 24×7 to answer all your WinTurbo queries. Ask me in your preferred language.',
  handoff_message text not null default 'I am transferring this conversation to the WinTurbo support team.',
  system_instructions text not null default 'Answer only questions about WinTurbo using approved knowledge. Match the user language. Never invent offers, transaction status, winning guarantees or account data. For account-specific, payment, dispute, withdrawal or responsible-play concerns, recommend human support.',
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);

create table if not exists public.chatbot_knowledge (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  category text not null default 'general',
  content text not null,
  language text not null default 'English',
  source_url text,
  status text not null default 'approved' check (status in ('draft','approved','rejected')),
  is_active boolean not null default true,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.chatbot_sessions (
  id uuid primary key default gen_random_uuid(),
  visitor_id text not null,
  origin text,
  ip_hash text,
  language text not null default 'Auto',
  status text not null default 'open' check (status in ('open','handoff','closed','blocked')),
  handoff_requested boolean not null default false,
  created_at timestamptz not null default now(),
  last_message_at timestamptz not null default now()
);

create table if not exists public.chatbot_messages (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.chatbot_sessions(id) on delete cascade,
  role text not null check (role in ('user','assistant','agent','system')),
  content text not null,
  language text not null default 'Auto',
  sources jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists chatbot_sessions_last_message_idx on public.chatbot_sessions(last_message_at desc);
create index if not exists chatbot_sessions_ip_idx on public.chatbot_sessions(ip_hash,last_message_at desc);
create index if not exists chatbot_messages_session_idx on public.chatbot_messages(session_id,created_at);
create index if not exists chatbot_knowledge_status_idx on public.chatbot_knowledge(status,is_active);

alter table public.chatbot_settings enable row level security;
alter table public.chatbot_knowledge enable row level security;
alter table public.chatbot_sessions enable row level security;
alter table public.chatbot_messages enable row level security;

